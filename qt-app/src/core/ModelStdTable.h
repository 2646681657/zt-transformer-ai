// 按系列+容量查标准值；非标准容量返回 nullptr
inline const StdEntry *lookup(const QString &series, double capacity_kVA)
{
    for (const auto &e : table(series)) {
        if (e.capacity_kVA == capacity_kVA) {
            return &e;
        }
    }
    return nullptr;
}

